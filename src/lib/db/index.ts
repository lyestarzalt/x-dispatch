import { app } from 'electron';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';
import * as fs from 'fs';
import * as path from 'path';
import { errorMessage } from '@/lib/utils/errors';
import logger from '@/lib/utils/logger';
import { type DatabaseSync, type SqliteDatabase, drizzleNodeSqlite, openSqlite } from './client';
import * as schema from './schema';

type DrizzleDatabase = SqliteDatabase<typeof schema>;

let db: DrizzleDatabase | null = null;
let sqlite: DatabaseSync | null = null;
let dbPath: string = '';
let migrationsFolder: string = '';

export function getDbPath(): string {
  return path.join(app.getPath('userData'), 'xplane-data.db');
}

/**
 * Read the current schema fingerprint from Drizzle's snapshot.
 * This ID is generated by `drizzle-kit generate` and changes whenever the schema changes.
 */
function getSchemaFingerprint(): string {
  const snapshotDir = path.join(migrationsFolder, 'meta');
  const files = fs
    .readdirSync(snapshotDir)
    .filter((f) => f.endsWith('_snapshot.json'))
    .sort();
  if (files.length === 0) throw new Error('No migration snapshots found in ' + snapshotDir);
  const latestFile = files[files.length - 1]!;
  const snapshot = JSON.parse(fs.readFileSync(path.join(snapshotDir, latestFile), 'utf-8'));
  if (!snapshot.id) throw new Error('Migration snapshot missing id field');
  return snapshot.id;
}

/**
 * Clean up leftover .old-* database files from previous failed deletions (Windows file lock workaround)
 * and temp files from interrupted saves of the old whole-file writer.
 */
function cleanupOldDbFiles(): void {
  try {
    const dir = path.dirname(dbPath);
    const base = path.basename(dbPath);
    for (const file of fs.readdirSync(dir)) {
      // Also temp files from a save cut short by a crash; each is a full copy of the DB.
      if (
        file.startsWith(base + '.old-') ||
        file === `${base}.tmp` ||
        file === `${base}.quit.tmp`
      ) {
        try {
          fs.unlinkSync(path.join(dir, file));
        } catch {
          /* still locked, will retry next launch */
        }
      }
    }
  } catch {
    /* non-critical */
  }
}

/**
 * Delete the database if its schema doesn't match the current Drizzle snapshot.
 * The DB is purely a cache of X-Plane files — all data is rescanned automatically.
 */
/**
 * Removes a database built by an older schema. Returns false when the file is
 * still in use and could not be unlinked or moved aside, which on Windows is a
 * virus scanner, the indexer, or the previous instance finishing its save.
 */
function deleteStaleDb(fingerprint: string): boolean {
  if (!fs.existsSync(dbPath)) return true;

  const versionPath = dbPath + '.version';
  let stored: string;

  try {
    stored = fs.existsSync(versionPath) ? fs.readFileSync(versionPath, 'utf-8').trim() : '';
  } catch {
    stored = '';
  }

  if (stored === fingerprint) return true;

  logger.data.info(`Schema changed — deleting stale database`);
  let removed = true;
  try {
    fs.unlinkSync(dbPath);
  } catch {
    try {
      fs.renameSync(dbPath, `${dbPath}.old-${Date.now()}`);
    } catch (err) {
      // The cache is rebuilt from X-Plane files either way, so a fresh database
      // overwrites the held file once the lock clears instead of blocking startup.
      logger.data.warn(`Stale database is in use, starting fresh: ${(err as Error).message}`);
      removed = false;
    }
  }
  try {
    fs.unlinkSync(versionPath);
  } catch {
    /* already gone */
  }
  return removed;
}

/**
 * Closes the database, deletes the cache files and relaunches; the next launch
 * rebuilds everything from X-Plane's files.
 */
function discardDbAndRelaunch(): void {
  try {
    sqlite?.close();
  } catch {
    /* already closed */
  }
  sqlite = null;
  db = null;
  try {
    if (fs.existsSync(dbPath)) fs.unlinkSync(dbPath);
  } catch {
    try {
      fs.renameSync(dbPath, `${dbPath}.old-${Date.now()}`);
    } catch {
      /* give up on cleanup */
    }
  }
  for (const suffix of ['-wal', '-shm']) {
    try {
      fs.rmSync(dbPath + suffix, { force: true });
    } catch {
      /* non-critical */
    }
  }
  try {
    if (fs.existsSync(dbPath + '.version')) fs.unlinkSync(dbPath + '.version');
  } catch {
    /* non-critical */
  }
  app.relaunch();
  app.exit(0);
}

const CORRUPTION_PATTERN =
  /database disk image is malformed|file is not a database|SQLITE_CORRUPT/i;

/**
 * Recovers from a corrupt cache found after startup: a file with an intact
 * header opens and migrates, then every launch fails on its first query
 * (Sentry X-DISPATCH-3E). Returns false, doing nothing, for any other error.
 */
export function recoverFromCorruption(err: unknown): boolean {
  const message = errorMessage(err);
  if (!dbPath || !CORRUPTION_PATTERN.test(message)) return false;
  logger.data.warn(`Database is corrupt, deleting and restarting: ${message}`);
  discardDbAndRelaunch();
  return true;
}

/** Empties a stale database that could not be deleted, so the migrations rebuild it in place. */
function dropAllTables(handle: DatabaseSync): void {
  const tables = handle
    .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")
    .all() as { name: string }[];
  for (const { name } of tables) handle.exec(`DROP TABLE IF EXISTS "${name}"`);
}

export async function initDb(): Promise<DrizzleDatabase> {
  if (db) return db;

  dbPath = getDbPath();
  migrationsFolder = path.join(app.getAppPath(), 'drizzle');

  logger.data.info(`Database initializing: ${dbPath}`);

  cleanupOldDbFiles();

  const fingerprint = getSchemaFingerprint();
  const staleRemoved = deleteStaleDb(fingerprint);

  // The DB is a cache — on any open error it is deleted and rebuilt from X-Plane files.
  try {
    fs.mkdirSync(path.dirname(dbPath), { recursive: true });
    sqlite = openSqlite(dbPath);
    // No fsync: an OS crash can at worst corrupt a cache that recovery deletes and rebuilds.
    // The larger checkpoint and page cache bring a full rescan back to sql.js speed.
    // TODO: SQLite documents WAL as unsupported on network filesystems, which userData sits on
    // under Windows folder redirection or an NFS home. If that shows up, set
    // `PRAGMA locking_mode = EXCLUSIVE` before WAL: the index then stays in memory, no -shm file.
    sqlite.exec(
      'PRAGMA journal_mode = WAL; PRAGMA synchronous = OFF; PRAGMA wal_autocheckpoint = 10000; PRAGMA cache_size = -32768;'
    );
    if (!staleRemoved) dropAllTables(sqlite);
    db = drizzleNodeSqlite(sqlite, schema);
    migrate(db as never, { migrationsFolder });
  } catch (err) {
    logger.data.warn(`Database open/migrate failed, deleting and restarting: ${err}`);
    discardDbAndRelaunch();
    throw err; // unreachable, but satisfies return type
  }

  fs.writeFileSync(dbPath + '.version', fingerprint);

  logger.data.info(`Database initialized: ${dbPath}`);
  return db;
}

export function getDb(): DrizzleDatabase {
  if (!db) {
    throw new Error('Database not initialized. Call initDb() first.');
  }
  return db;
}

/** True once initDb() has assigned the singleton. Use this to gate read-only
 * callers that fire before app startup completes (e.g. the renderer asking
 * for a status snapshot while initDb is still running). */
export function isDbReady(): boolean {
  return db !== null;
}

/** Raw node:sqlite handle for debug queries — only use in dev tools */
export function getSqlite(): DatabaseSync | null {
  return sqlite;
}

export function closeDb(): void {
  if (sqlite) {
    sqlite.close();
    sqlite = null;
    db = null;
  }
}

export * from './schema';
